import { mkdtemp, rm } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest';
import { compilePreviewRuntime } from '../scripts/telegram-preview.mjs';
import { buildOfficialPreview, loadOfficialSpec, COMMIT, SPEC_SHA256 } from '../scripts/telegram-preview-oficial.mjs';

let temp, runtime, spec;
beforeAll(async () => {
  vi.stubGlobal('fetch', vi.fn(() => { throw new Error('No real network'); }));
  spec = await loadOfficialSpec();
  temp = await mkdtemp(path.join(os.tmpdir(), 'itad-official-test-'));
  runtime = await compilePreviewRuntime(temp);
}, 30_000);
afterAll(async () => {
  expect(fetch).not.toHaveBeenCalled();
  vi.unstubAllGlobals();
  if (temp) await rm(temp, { recursive: true, force: true });
});

describe('official local preview generated by real compiled v4 formatters', () => {
  it('embeds exact unmodified Rich parts, with no provenance inside cards', () => {
    const { html, groups } = buildOfficialPreview(runtime, spec);
    const detail = spec.components.examples['resp.notifications.waitlist.get.v1'].value;
    const bundle = runtime.parseBundles(spec.components.examples['resp.bundles.v1.success'].value)[0].bundle;
    expect(groups).toEqual([
      runtime.formatNotification(runtime.parseWaitlistNotification(detail)),
      runtime.formatBundle({ bundle, waitlist: [], collection: [] }).map(runtime.stripImages),
    ]);
    const cards = [...html.matchAll(/<article class="rich-card">([\s\S]*?)<\/article>/g)].map(match => match[1]);
    expect(cards).toEqual(groups.flat());
    expect(cards).toHaveLength(2);
    expect(cards[0]).toContain('<h4>13,99\u00a0€</h4>');
    expect(cards[0]).toContain('<p>Mínimo histórico: 6,99\u00a0€</p>');
    expect(cards[0]).not.toMatch(/>-0%|Gratis|Cupón:|Caduca:|Hasta/);
    expect(cards[1]).toContain('<h4>Nivel 1 · 87,96\u00a0US$</h4>');
    expect(bundle.note).toBe('* Bundle being relaunched...again and again.');
    expect(cards[1]).not.toMatch(/Nota de ITAD|Bundle being relaunched|Caduca:/);
    expect(cards[1]).toContain('<footer>Hasta el 22 de marzo</footer>');
    expect(html).toContain(bundle.note); // Official source remains available outside the cards.
    for (const card of cards) expect(card).not.toMatch(/Fuente:|provenance|placeholder|simulad|<style|<img/);
    for (const part of groups.flat()) expect(Buffer.byteLength(part)).toBeLessThanOrEqual(30_000);
  });

  it('is offline, mobile-first, historically labelled and pinned to verifiable public sources', () => {
    const { html } = buildOfficialPreview(runtime, spec);
    expect(html).toContain('width=device-width');
    expect(html).toContain('width:min(100%,390px)');
    expect(html).toContain("default-src 'none'");
    expect(html).toContain("connect-src 'none'");
    expect(html).not.toMatch(/<script|<link|<img|<iframe|@import|url\(/i);
    expect(html).toContain(COMMIT);
    expect(html).toContain(SPEC_SHA256);
    expect(html).toContain('históricos de 2024');
    expect(html).toContain('waitlist=[] y collection=[]');
    expect(html).toContain('/bundles/v2 no existe');
    expect(html).toContain('87,96 US$');
    expect(html).not.toContain('Nebula');
  });
});
